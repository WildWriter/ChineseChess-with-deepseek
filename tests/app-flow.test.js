import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { once } from 'node:events';
import { JSDOM } from 'jsdom';
import { createApp } from '../server.js';
import { detailedAnswer } from './model-fixture.js';

test('full page connects training AI, manual sandbox and imported step coaching through HTTP', async t => {
  const requests = [];
  let rejectTeaching=false;
  const server = createApp({ engineReady: () => false, fetchImpl: async (url, options) => {
    const context = JSON.parse(JSON.parse(options.body).messages[1].content); requests.push(context);
    const answer=detailedAnswer(context);if(rejectTeaching)answer.steps[0].responses.pop();
    return { ok: true, json: async () => ({ choices: [{ finish_reason: 'stop', message: { content: JSON.stringify(answer) } }] }) };
  } });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  const base = `http://127.0.0.1:${server.address().port}`;
  const dom = new JSDOM(await readFile(new URL('../public/index.html', import.meta.url), 'utf8'), { url: base });
  const keys = ['window', 'document', 'Option', 'location', 'localStorage', 'history', 'fetch', 'setTimeout'];
  const saved = Object.fromEntries(keys.map(key => [key, globalThis[key]])), timers = new Set();
  for (const key of keys.slice(0, 6)) globalThis[key] = dom.window[key];
  globalThis.fetch = (url, options) => saved.fetch(new URL(url, base), options);
  globalThis.setTimeout = (callback, delay, ...args) => { const timer = saved.setTimeout(callback, delay, ...args); timers.add(timer); return timer; };
  const $ = id => document.getElementById(id);
  async function until(predicate) { for (let n = 0; n < 150; n++) { if (predicate()) return; await new Promise(resolve => saved.setTimeout(resolve, 20)); } assert.fail('Page operation did not complete'); }
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); for (const timer of timers) clearTimeout(timer); dom.window.close(); for (const key of keys) globalThis[key] = saved[key]; });
  await import('../public/app.js'); await until(() => Boolean($('position-example').onclick));
  assert.ok(!$('feedback').textContent.includes('初始化失败'), $('feedback').textContent);
  await $('lesson-button').onclick(); assert.equal($('report-content').querySelectorAll('.walkthrough').length, 1);
  assert.equal($('report-title').textContent, '本地解法回放');
  assert.ok($('report-content').querySelectorAll('.position-line li').length);
  assert.equal($('report-content').querySelector('.step-explanation'), null);
  assert.equal($('report-content').querySelector('.walkthrough-summary'), null);
  assert.equal(document.querySelector('.short-mate-options').open,false);
  $('api-key-input').value = 'page-mock-only'; $('apply-api-button').onclick();
  await $('ai-button').onclick(); assert.equal($('report-title').textContent, 'AI 复盘讲解');
  const training = $('report-content').querySelector('.walkthrough');
  assert.match(training.querySelector('.teaching-source').textContent,/DS 逐步讲解/);
  [...training.querySelectorAll('button')].find(node => node.textContent === '从此处开始摆谱').click();
  training.querySelector('[data-square="a1"]').dispatchEvent(new dom.window.MouseEvent('click'));
  training.querySelector('[data-square="a2"]').dispatchEvent(new dom.window.MouseEvent('click'));
  [...training.querySelectorAll('button')].find(node=>node.textContent==='AI 分析当前局面').click();
  await until(() => training.querySelector('.study-status').dataset.state === 'success');
  assert.equal(requests.at(-1).lastPlayed.move, 'a1a2'); assert.match(training.querySelector('.study-analysis h2').textContent, /分支第 1 步/);
  [...training.querySelectorAll('button')].find(node => node.textContent === '返回主线讲解').click();
  document.querySelector('[data-view="import"]').onclick(); $('position-example').onclick();
  assert.equal($('position-grid-panel').hidden, false); assert.equal($('position-grid-editor').hidden, true);
  $('position-confirm').checked = true; $('position-confirm').onchange();
  const solving = $('position-solve').onclick();
  assert.equal($('position-solve').disabled, true); assert.equal($('position-solve').getAttribute('aria-busy'), 'true');
  assert.equal($('position-action-status').dataset.state, 'pending');
  await solving;
  assert.equal($('position-report').hidden, false); assert.equal($('position-walkthrough').hidden, true);
  assert.equal($('position-walkthrough').textContent, '');
  assert.equal($('position-line').children.length, 3); assert.ok($('position-evidence').children.length);
  $('position-playback').value='1'; $('position-playback').onchange({target:$('position-playback')});
  assert.match($('position-board-turn').textContent, /线路第 1 步/);
  $('position-study').click();
  assert.equal($('position-walkthrough').hidden, false);
  assert.match($('position-walkthrough').querySelector('.study-board-panel>strong').textContent, /自由摆谱/);
  assert.equal($('position-walkthrough').querySelector('.step-explanation').textContent, '');
  [...$('position-walkthrough').querySelectorAll('button')].find(node=>node.textContent==='返回参考线路').click();
  assert.equal($('position-walkthrough').hidden, true); assert.equal($('position-playback').value, '1');
  assert.equal(document.activeElement, $('position-report'));
  assert.equal($('position-solve').getAttribute('aria-busy'), 'false');
  const explaining = $('position-explain').onclick();
  assert.equal($('position-walkthrough').hidden, true); assert.equal($('position-walkthrough').textContent, '');
  await explaining; assert.equal($('position-ai-report').hidden, false);
  assert.equal($('position-walkthrough').hidden, false);
  assert.match($('position-walkthrough').querySelector('.teaching-source').textContent, /DS 逐步讲解/);
  assert.ok(requests.at(-1).walkthrough.steps[0].reason.length);
  assert.ok(requests.at(-1).walkthrough.steps[0].alternatives.length);
  const select = $('position-walkthrough').querySelector('.walkthrough-nav select'); select.value = '1'; select.dispatchEvent(new dom.window.Event('change'));
  assert.equal($('position-playback').value, '1'); assert.match($('position-walkthrough').querySelector('.step-explanation .eyebrow').textContent, /2 \/ 3/);
  assert.equal(requests.length, 3);
  rejectTeaching=true;const preservedFen=$('position-fen').value;
  await $('position-explain').onclick();
  assert.match($('position-action-status').textContent,/第 1 步.*对方应对.*没有完整覆盖/);
  assert.equal($('position-fen').value,preservedFen);assert.equal($('position-report').hidden,false);
  assert.equal($('position-ai-report').hidden,true);assert.equal($('position-explain').disabled,false);
  assert.equal($('position-walkthrough').hidden, true); assert.equal($('position-walkthrough').textContent, '');
  assert.equal($('position-ai-content').textContent, ''); assert.equal($('position-line').children.length, 3);
  assert.equal(requests.length,4);
  document.querySelector('[data-view="training"]').onclick();
  await $('ai-button').onclick();
  assert.match($('ai-caption').textContent, /讲解调用失败/);
  assert.equal($('report-panel').hidden, true);
  assert.equal($('report-content').textContent, '');
  assert.equal($('report-content').querySelectorAll('.position-line li').length, 0);
  assert.equal($('report-content').querySelector('.step-explanation'), null);
  assert.equal($('report-content').querySelector('.walkthrough-summary'), null);
  assert.ok(!$('report-content').textContent.includes('已切换为本地规则说明'));
  document.querySelector('[data-view="import"]').onclick();
  $('position-clear').onclick(); $('position-confirm').checked = true; $('position-confirm').onchange();
  await $('position-solve').onclick();
  assert.equal($('position-action-status').dataset.state, 'error');
  assert.match($('position-action-status').textContent, /求解失败：未找到红帅/);
  assert.equal($('position-action-status').textContent, $('position-status').textContent);
  assert.equal($('position-report').hidden, true); assert.equal($('position-solve').disabled, false);
  assert.equal($('position-solve').getAttribute('aria-busy'), 'false');
});
